/**
 * Issue #700: `what was $500 worth in 1965` was refused, because the bundled
 * price index started in 1970, and the figures it did hold were recalled from
 * general knowledge rather than taken from the published series (2025 read
 * 322.2 against the published 321.943). The table is now generated by
 * `scripts/build-cpi-table.mjs` from BLS series CUUR0000SA0, every year from
 * 1913 to the latest month published, and the CSV it was built from is
 * recorded in `scripts/fixtures/cpi/cpiai.csv`.
 *
 * The boundary: the index is still the US CPI-U, applied only to US dollars
 * (#650; the pound and the euro read their own indices since #756), and inflation still makes no
 * network call when a line is evaluated. The script is a build step.
 */

afterEach(removeTempTrees);

const SCRIPT = "build-cpi-table.mjs";
const FIXTURE = path.join(REPO_ROOT, "scripts/fixtures/cpi/cpiai.csv");
const FIXTURE_TEXT = fs.readFileSync(FIXTURE, "utf8");
const TABLE_FILE = path.join(REPO_ROOT, "packages/engine/src/packages/finance/data/CpiTable.ts");

/** 11 March 2026, noon UTC: the clock the docs examples run on, so a present-year line has a fixed answer. */
const NOW_2026 = Date.UTC(2026, 2, 11, 12, 0, 0);

/** An engine whose present year is 2026 whatever the real clock says. */
function engine2026() {
	return newTrackedEngine({ calendar: new RecordingCalendar(NOW_2026, dateCalendarInZone("UTC")) });
}

function shown(line: string): string {
	return formatValue(engine2026().evaluateExpression(line));
}

function code(line: string): string | undefined {
	return engine2026().evaluateExpression(line).errorCode;
}

interface Observation { year: number; month: number; value: number; decimals: number }
interface YearAverage { year: number; value: number; decimals: number; months: number; source: string }
interface Averages { years: YearAverage[]; partial: { year: number; months: number[] } | null }

/** The script's message for a call expected to be refused, or "" when it was not. */
function refusal(exportName: string, args: readonly unknown[]): string {
	try {
		callExport(SCRIPT, exportName, args);
		return "";
	} catch (error) {
		return String((error as Error).message);
	}
}

/** The fixture with some of its data rows changed: `edit` maps each data line to its replacement (or null to drop it). */
function editedFixture(edit: (line: string) => string | null | string[]): string {
	const [header, ...rows] = FIXTURE_TEXT.trimEnd().split("\n");
	const out: string[] = [header];
	for (const row of rows) {
		const next = edit(row);
		if (next === null) continue;
		if (Array.isArray(next)) out.push(...next);
		else out.push(next);
	}
	return `${out.join("\n")}\n`;
}

/**
 * The fixture's months as BLS public API responses, one per 20-year window as
 * the script asks for them: value text exactly as recorded, October 2025 as the
 * `-` BLS returns for a month it has no value for, and the M13 annual averages
 * the issue quotes for 2024 and 2025. Built from the recorded CSV, since this
 * environment cannot reach api.bls.gov; the shape is the API's documented one.
 */
function blsResponses(): unknown[] {
	const rows = FIXTURE_TEXT.trimEnd().split("\n").slice(1).map((l) => l.split(","));
	const responses: unknown[] = [];
	for (let start = 1913; start <= 2026; start += 20) {
		const end = Math.min(start + 19, 2026);
		const data: unknown[] = [];
		for (const [date, value] of rows) {
			const year = Number(date.slice(0, 4));
			if (year < start || year > end) continue;
			data.push({ year: String(year), period: `M${date.slice(5, 7)}`, periodName: "", value, footnotes: [{}] });
		}
		if (start <= 2025 && end >= 2025) {
			data.push({ year: "2025", period: "M10", periodName: "October", value: "-", footnotes: [{ code: "X", text: "Data unavailable due to the 2025 lapse in appropriations." }] });
			data.push({ year: "2025", period: "M13", periodName: "Annual", value: "321.943", footnotes: [{}] });
			data.push({ year: "2024", period: "M13", periodName: "Annual", value: "313.689", footnotes: [{}] });
		}
		responses.push({ status: "REQUEST_SUCCEEDED", responseTime: 100, message: [], Results: { series: [{ seriesID: "CUUR0000SA0", data }] } });
	}
	return responses;
}

