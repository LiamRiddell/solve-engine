describe("adversarial lines", () => {
	test("prototype words where a year goes are honest, and Object.prototype is unchanged", () => {
		expectPrototypeUntouched(() => {
			for (const word of PROTOTYPE_WORDS) {
				expectHonestLine(`what is $100 from ${word}`, { engine: engine2026() });
				expectHonestLine(`what was $500 worth in ${word}`, { engine: engine2026() });
				expectHonestLine(`inflationAdjust($100, ${word}, 2020)`);
			}
		});
	});

	test("numeric edges where a year goes are honest, and never a number for a year outside 1913 to 2026", () => {
		for (const line of fill("inflationAdjust($100, X, 2020)", NUMERIC_EDGES)) expectHonestLine(line, { allowNaN: true });
		for (const line of fill("what was $500 worth in X", NUMERIC_EDGES)) expectHonestLine(line, { engine: engine2026(), allowNaN: true });
		for (const year of ["0", "-1913", "2026.5e3", "2^53", "1e308"]) {
			expect({ year, code: code(`inflationAdjust($100, ${year}, 2020)`) }).toEqual({ year, code: "INFLATION_YEAR_OUT_OF_RANGE" });
		}
		// A fraction is not a year at all, in range or not (see FoundBug_inflationYear.spec.ts).
		expect(code("inflationAdjust($100, 1912.999, 2020)")).toBe("INFLATION_EXPECTED_YEAR");
	});

	test("text edges around the form are honest", () => {
		for (const text of TEXT_EDGES) expectHonestLine(`what was $500 worth in 1965 ${text}`, { engine: engine2026() });
	});

	test("a long run of inflation lines stays within its budget", () => {
		const doc = Array.from({ length: 500 }, (_, i) => `inflationAdjust($100, ${1913 + (i % 114)}, 2026)`).join("\n");
		expectHonestDocument(doc, { budgetMs: 20_000 });
	});

	test("realistic breakage: a typo, pounds, a bare number and a value from the line above", () => {
		expect(expectHonestLine("what was $500 worth in 1965x", { engine: engine2026() }).kind).not.toBe("value");
		// Pounds read the UK index since #756; a bare number is still refused.
		expect(shown("what was £500 worth in 1965")).toBe("= £17.92");
		expect(code("what was 500 worth in 1965")).toBe("INFLATION_NO_INDEX");
		const { batch } = expectHonestDocument("year = 1913\ninflationAdjust($1, year, year + 113)");
		expect(batch[1]).toBe("= $33.45");
	});
});
