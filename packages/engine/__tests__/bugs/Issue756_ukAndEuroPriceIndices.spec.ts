/** 11 March 2026, noon UTC: the clock the docs examples run on, so a present-year line has a fixed answer. */
const NOW_2026 = Date.UTC(2026, 2, 11, 12, 0, 0);

function engine2026() {
	return newTrackedEngine({ calendar: new RecordingCalendar(NOW_2026, dateCalendarInZone("UTC")) });
}

function shown(line: string): string {
	return formatValue(engine2026().evaluateExpression(line));
}

function code(line: string): string | undefined {
	return engine2026().evaluateExpression(line).errorCode;
}

interface Annual { year: number; value: number; decimals: number }
interface Monthly { year: number; month: number; value: number; decimals: number }
interface Series { years: Array<{ year: number; value: number; decimals: number; months: number; source?: string }>; partial: { year: number; months: number[] } | null }

/** The script's message for a call expected to be refused, or "" when it was not. */
function refusal(script: string, exportName: string, args: readonly unknown[]): string {
	try {
		callExport(script, exportName, args);
		return "";
	} catch (error) {
		return String((error as Error).message);
	}
}

/** A CSV's data rows changed: `edit` maps each row to its replacement, a list of rows, or null to drop it. */
function edited(text: string, edit: (line: string) => string | null | string[]): string {
	const [header, ...rows] = text.trimEnd().split("\n");
	const out: string[] = [header];
	for (const row of rows) {
		const next = edit(row);
		if (next === null) continue;
		if (Array.isArray(next)) out.push(...next);
		else out.push(next);
	}
	return `${out.join("\n")}\n`;
}

const ONS_MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];

/**
 * The recorded figures in the ONS generator's CSV shape: a metadata block,
 * then every period quoted, years first, then quarters, then months, as the
 * generator writes it. Built from the recording, since this environment
 * cannot reach www.ons.gov.uk; the shape is the generator's.
 */
function onsCsv(cdid = "CDKO"): string {
	const lines = [
		'"Title","Long term indicator of prices of consumer goods and services: Jan 1974=100"',
		`"CDID","${cdid}"`,
		'"Source dataset ID","MM23"',
		'"PreUnit",""',
		'"Unit","Index, base year = 100"',
		'"Release date","17-09-2026"',
		'"Next release","21 October 2026"',
		'"Important notes",""',
	];
	for (const row of UK_ANNUAL_TEXT.trimEnd().split("\n").slice(1)) {
		const [year, value] = row.split(",");
		lines.push(`"${year}","${value}"`);
	}
	lines.push('"1947 Q3","29.2"');
	for (const row of UK_MONTHLY_TEXT.trimEnd().split("\n").slice(1)) {
		const [date, value] = row.split(",");
		lines.push(`"${date.slice(0, 4)} ${ONS_MONTHS[Number(date.slice(5, 7)) - 1]}","${value}"`);
	}
	return `${lines.join("\n")}\n`;
}

