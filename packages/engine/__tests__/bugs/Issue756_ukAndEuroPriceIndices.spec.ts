/**
 * Issue #756: the inflation forms read one table, the US CPI-U, whatever the
 * amount's currency, so `what is £100 from 1990` was £254.55, the American
 * figure with a pound sign (refused since #650). The amount's currency now
 * picks the index: US dollars read the BLS CPI-U (#700), pounds sterling the
 * ONS long-term indicator of consumer prices, series CDKO, and euros the
 * euro-area HICP, from the ECB's monthly series ICP.M.U2.N.000000.4.INX. Each
 * table is generated by a script from a recorded snapshot, in #700's shape.
 *
 * The boundary: CDKO is the ONS's own long-run series, which chains RPI-era
 * data before the CPI's start; it is none of CPI, CPIH or RPI alone. The
 * euro-area index starts in 1996 but the euro in 1999, so a euro year before
 * 1999 is refused, and the ECB's series ends with December 2025 (the dataset
 * was discontinued in February 2026), so a euro line that runs to 2026 is
 * refused. Every other currency keeps a refusal, and so does a bare number.
 */

