describe("adversarial lines", () => {
	test("prototype words as the currency or the year are honest, and Object.prototype is unchanged", () => {
		expectPrototypeUntouched(() => {
			for (const word of PROTOTYPE_WORDS) {
				expectHonestLine(`what is £100 from ${word}`, { engine: engine2026() });
				expectHonestLine(`inflationAdjust(€100, ${word}, 2020)`);
				expectHonestLine(`inflationAdjust(100 ${word}, 1990, 2020)`);
				expectHonestLine(`what is 100 ${word} from 1990`, { engine: engine2026() });
				expectHonestLine(`100 ${word} in 1990 dollars`, { engine: engine2026() });
			}
		});
	});

	test("numeric edges as the year or the amount are honest, and never a number outside each range", () => {
		for (const line of fill("inflationAdjust(£100, X, 2020)", NUMERIC_EDGES)) expectHonestLine(line, { allowNaN: true });
		for (const line of fill("inflationAdjust(€100, 2000, X)", NUMERIC_EDGES)) expectHonestLine(line, { allowNaN: true });
		for (const line of fill("what was £X worth in 1965", NUMERIC_EDGES)) expectHonestLine(line, { engine: engine2026(), allowNaN: true });
		for (const year of ["0", "-1990", "1799.999", "2^53", "1e308"]) {
			expect({ year, code: code(`inflationAdjust(£100, ${year}, 2020)`) }).toEqual({ year, code: "INFLATION_YEAR_OUT_OF_RANGE" });
			expect({ year, code: code(`inflationAdjust(€100, ${year}, 2020)`) }).toEqual({ year, code: "INFLATION_YEAR_OUT_OF_RANGE" });
		}
	});

	test("zero, negative zero and negative amounts", () => {
		expect(shown("inflationAdjust(£0, 1990, 2020)")).toBe("= £0.00");
		expect(shown("inflationAdjust(-£100, 2024, 2025)")).toBe("= -£104.14");
		expectHonestLine("inflationAdjust(-£0, 1990, 2020)");
	});

	test("text edges around the form are honest", () => {
		for (const text of TEXT_EDGES) expectHonestLine(`what was £500 worth in 1965 ${text}`, { engine: engine2026() });
		for (const text of TEXT_EDGES) expectHonestLine(`inflationAdjust(€100, 2000, 2020) ${text}`);
	});

	test("a long run of inflation lines in every currency stays within its budget", () => {
		const doc = Array.from({ length: 600 }, (_, i) => {
			if (i % 3 === 0) return `inflationAdjust(£100, ${1800 + (i % 227)}, 2026)`;
			if (i % 3 === 1) return `inflationAdjust(€100, ${1999 + (i % 27)}, 2025)`;
			return `inflationAdjust($100, ${1913 + (i % 114)}, 2026)`;
		}).join("\n");
		expectHonestDocument(doc, { budgetMs: 20_000 });
	});

	test("realistic breakage: a typo, the pound's own phrase for dollars, and a value from the line above", () => {
		expect(expectHonestLine("what is £100 form 1990", { engine: engine2026() }).kind).not.toBe("value");
		expect(expectHonestLine("what was £500 worth in 1965x", { engine: engine2026() }).kind).not.toBe("value");
		const { batch } = expectHonestDocument("year = 1999\ninflationAdjust(€1, year, year + 26)");
		expect(batch[1]).toBe("= €1.73");
	});
});
