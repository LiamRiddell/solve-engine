/**
 * Regenerates the bundled UK price index, `packages/engine/src/packages/finance/data/UkCpiTable.ts`,
 * from the Office for National Statistics series CDKO (#756).
 *
 * CDKO is the ONS's own long-run consumer price series, the long-term indicator
 * of prices of consumer goods and services (January 1974 = 100). It chains
 * RPI-era data before the CPI's start, so one series runs from 1800 to the
 * latest month published. It is none of CPI, CPIH or RPI on its own, and the
 * table says so.
 *
 * It is a build step, not a runtime fetch, in the shape of the US table's
 * script (`build-cpi-table.mjs`, #700). The series comes from one of two places:
 *
 *   - `--from-ons`: the ONS time-series generator, the primary source
 *     ({@link ONS_URL}), whose CSV carries the annual, quarterly and monthly
 *     figures in one file. Needs network access to www.ons.gov.uk.
 *   - `--from-mirror=<dir>`: a directory holding the Frictionless Data mirror
 *     of the same series (github.com/datasets/cpi-uk): `cpi-uk-annual.csv`
 *     (`Year,Price Index`) and `cpi-uk-monthly.csv` (`Date,Price Index`). The
 *     default is the recorded snapshot in `scripts/fixtures/cpi/`, which is
 *     what the committed table was built from, so a plain run reproduces it.
 *
 * Where the files came from and when they were retrieved are recorded beside
 * them, in `cpi-uk.source.json` (`{ "source", "retrieved" }`), which
 * `--save-csv` writes after an ONS fetch; a directory without one needs
 * `--retrieved=YYYY-MM-DD`.
 *
 * The method: every year ONS publishes an annual figure for is that figure, as
 * published. A later year that has only monthly figures (the current one) is
 * the mean of its months, rounded to the one decimal ONS publishes, and is
 * marked partial when it stops before December. Each finished year present in
 * both files is checked: the mean of its twelve months must lie within
 * {@link ANNUAL_TOLERANCE} of the published annual figure. ONS averages the
 * unrounded months, so the two differ by rounding and nothing more; a wider gap
 * means the two files are not the same series, and the build is refused.
 *
 * Every refusal is an Error whose message starts with a name in capitals
 * (`CPI_CSV_BAD_HEADER: ...`), so a test or a maintainer can tell which check
 * failed.
 *
 * Usage:
 *   npm run data:cpi                                       rebuild every bundled index
 *   npm run data:cpi -- --check                            exit 1 when a committed table differs
 *   node scripts/build-uk-cpi-table.mjs --check
 *   node scripts/build-uk-cpi-table.mjs --from-mirror=<dir> --retrieved=2026-10-01
 *   node scripts/build-uk-cpi-table.mjs --from-ons --save-csv=scripts/fixtures/cpi
 *   node scripts/build-uk-cpi-table.mjs --out=<file>       write somewhere other than the engine
 *
 * @module build-uk-cpi-table
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { readIndex, roundTo } from "./build-cpi-table.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The series the table is built from. */
export const SERIES_ID = "CDKO";

/** The first year the series has. */
export const FIRST_YEAR = 1800;

/** The ONS generator's CSV of the series. */
export const ONS_URL = "https://www.ons.gov.uk/generator?format=csv&uri=/economy/inflationandpriceindices/timeseries/cdko/mm23";

/** Where the generated table lives. */
export const TABLE_PATH = path.join(REPO, "packages/engine/src/packages/finance/data/UkCpiTable.ts");

/** The directory holding the recorded snapshot the committed table was built from. */
export const FIXTURE_DIR = path.join(REPO, "scripts/fixtures/cpi");

/** The mirror's file names, and the record of where they came from. */
export const ANNUAL_FILE = "cpi-uk-annual.csv";
export const MONTHLY_FILE = "cpi-uk-monthly.csv";
export const SOURCE_FILE = "cpi-uk.source.json";

/** The line that ends the generated part of the table file; what follows it is kept as written. */
export const END_MARKER = "// END GENERATED BY scripts/build-uk-cpi-table.mjs";

/**
 * How far the mean of a finished year's monthly figures may lie from the
 * published annual figure, in index points. The recorded series differs by at
 * most 0.21 (1993), all of it rounding: ONS averages the unrounded months.
 */
export const ANNUAL_TOLERANCE = 0.25;

/** The largest source accepted, in bytes. The real files are 3 KB and 17 KB. */
export const MAX_SOURCE_BYTES = 1024 * 1024;

/** The most annual rows accepted, three centuries with room to spare. */
export const MAX_ANNUAL_ROWS = 400;

/** The most monthly rows accepted, two centuries of months. */
export const MAX_MONTHLY_ROWS = 12 * 200;

const MONTH_NAMES = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const ONS_MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];

/** A named refusal. */
function refuse(name, detail) {
	return new Error(`${name}: ${detail}`);
}

/** `2025-10` for a year and a one-based month. */
function monthKey(year, month) {
	return `${year}-${String(month).padStart(2, "0")}`;
}

/** The text's lines, a byte-order mark and trailing blank lines removed, after the size check. */
function linesOf(text) {
	if (typeof text !== "string") throw refuse("CPI_NO_DATA", "the source is not text");
	if (Buffer.byteLength(text, "utf8") > MAX_SOURCE_BYTES) throw refuse("CPI_SOURCE_TOO_LARGE", `the source is larger than ${MAX_SOURCE_BYTES} bytes`);
	const lines = text.replace(/^﻿/, "").split(/\r?\n/);
	while (lines.length > 0 && lines[lines.length - 1].trim() === "") lines.pop();
	if (lines.length === 0) throw refuse("CPI_NO_DATA", "the source is empty");
	return lines;
}

/** Check a year read from a source: a whole number from 1800 on. */
function checkYear(year, where) {
	if (!Number.isInteger(year) || year < FIRST_YEAR || year > 9999) throw refuse("CPI_BAD_DATE", `${where} has the year ${year}, outside the series, which starts in ${FIRST_YEAR}`);
}

/**
 * Check a list of annual figures and order it: each year in range, none twice.
 *
 * @param annual - `{ year, value, decimals }` each.
 * @returns The same figures sorted by year.
 */
export function checkAnnual(annual) {
	if (!Array.isArray(annual) || annual.length === 0) throw refuse("CPI_NO_DATA", "the source has no annual figures");
	if (annual.length > MAX_ANNUAL_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${annual.length} years, more than the ${MAX_ANNUAL_ROWS} accepted`);
	const seen = new Map();
	for (const a of annual) {
		checkYear(a.year, String(a.year));
		if (seen.has(a.year)) throw refuse("CPI_DUPLICATE_YEAR", `${a.year} appears twice`);
		seen.set(a.year, a);
	}
	return [...seen.values()].sort((a, b) => a.year - b.year);
}

/**
 * Check a list of monthly figures and order it: each year and month in range,
 * no month twice. An empty list is allowed: the annual figures stand alone.
 *
 * @param monthly - `{ year, month, value, decimals }` each, month one-based.
 * @returns The same figures sorted by date.
 */
export function checkMonthly(monthly) {
	if (!Array.isArray(monthly)) throw refuse("CPI_NO_DATA", "the monthly figures are not a list");
	if (monthly.length > MAX_MONTHLY_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${monthly.length} months, more than the ${MAX_MONTHLY_ROWS} accepted`);
	const seen = new Map();
	for (const o of monthly) {
		checkYear(o.year, String(o.year));
		if (!Number.isInteger(o.month) || o.month < 1 || o.month > 12) throw refuse("CPI_BAD_DATE", `${o.year} has a month numbered ${o.month}`);
		const key = monthKey(o.year, o.month);
		if (seen.has(key)) throw refuse("CPI_DUPLICATE_MONTH", `${key} appears twice`);
		seen.set(key, o);
	}
	return [...seen.values()].sort((a, b) => a.year - b.year || a.month - b.month);
}

/**
 * Parse the mirror's annual CSV: a `Year,Price Index` header, then one row per year.
 *
 * @param text - The file's text, LF or CRLF, with or without a trailing newline.
 * @returns The annual figures, checked and sorted.
 */
export function parseAnnualCsv(text) {
	const lines = linesOf(text);
	if (lines[0].trim() !== "Year,Price Index") throw refuse("CPI_CSV_BAD_HEADER", `the annual header is "${lines[0].slice(0, 80)}", not "Year,Price Index"`);
	if (lines.length - 1 > MAX_ANNUAL_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the annual source has ${lines.length - 1} rows, more than the ${MAX_ANNUAL_ROWS} accepted`);
	const annual = [];
	for (let i = 1; i < lines.length; i++) {
		const where = `line ${i + 1}`;
		const cells = lines[i].split(",");
		if (cells.length !== 2) throw refuse("CPI_CSV_BAD_ROW", `${where} has ${cells.length} cells, not 2`);
		const year = /^(\d{4})$/.exec(cells[0].trim());
		if (!year) throw refuse("CPI_BAD_DATE", `${where} has the year "${cells[0].trim().slice(0, 40)}", not a year written YYYY`);
		checkYear(Number(year[1]), where);
		annual.push({ year: Number(year[1]), ...readIndex(cells[1], where) });
	}
	if (annual.length === 0) throw refuse("CPI_NO_DATA", "the annual source has no rows");
	return checkAnnual(annual);
}

/**
 * Parse the mirror's monthly CSV: a `Date,Price Index` header, then one row per
 * month dated the first of the month.
 *
 * @param text - The file's text, LF or CRLF, with or without a trailing newline.
 * @returns The monthly figures, checked and sorted.
 */
export function parseMonthlyCsv(text) {
	const lines = linesOf(text);
	if (lines[0].trim() !== "Date,Price Index") throw refuse("CPI_CSV_BAD_HEADER", `the monthly header is "${lines[0].slice(0, 80)}", not "Date,Price Index"`);
	if (lines.length - 1 > MAX_MONTHLY_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the monthly source has ${lines.length - 1} rows, more than the ${MAX_MONTHLY_ROWS} accepted`);
	const monthly = [];
	for (let i = 1; i < lines.length; i++) {
		const where = `line ${i + 1}`;
		const cells = lines[i].split(",");
		if (cells.length !== 2) throw refuse("CPI_CSV_BAD_ROW", `${where} has ${cells.length} cells, not 2`);
		const date = /^(\d{4})-(\d{2})-01$/.exec(cells[0].trim());
		if (!date) throw refuse("CPI_BAD_DATE", `${where} has the date "${cells[0].trim().slice(0, 40)}", not the first of a month written YYYY-MM-01`);
		monthly.push({ year: Number(date[1]), month: Number(date[2]), ...readIndex(cells[1], where) });
	}
	return checkMonthly(monthly);
}

/** One cell of the ONS generator's CSV, which quotes every cell: `"1947 JUN"` is `1947 JUN`. */
function onsCell(text) {
	const s = text.trim();
	return s.length >= 2 && s.startsWith('"') && s.endsWith('"') ? s.slice(1, -1) : s;
}

/**
 * Parse the ONS generator's CSV for {@link SERIES_ID}: a block of metadata
 * rows (`"Title","..."`, `"CDID","CDKO"`, `"Release date","..."`), then one
 * row per period, `"1800","13.5"` for a year, `"1947 Q2","28.9"` for a quarter
 * and `"1947 JUN","28.9"` for a month. Quarters are not used. The CDID row must
 * name the series, so another series' file is refused rather than tabled.
 *
 * @param text - The file's text.
 * @returns `{ annual, monthly }`, each checked and sorted.
 */
export function parseOnsCsv(text) {
	const lines = linesOf(text);
	const annual = [];
	const monthly = [];
	let cdid;
	let inData = false;
	for (let i = 0; i < lines.length; i++) {
		const where = `line ${i + 1}`;
		const cells = lines[i].split('","');
		if (cells.length !== 2) throw refuse("CPI_CSV_BAD_ROW", `${where} has ${cells.length} cells, not 2`);
		const label = onsCell(`${cells[0]}"`);
		const value = onsCell(`"${cells[1]}`);
		const year = /^(\d{4})$/.exec(label);
		const quarter = /^(\d{4}) Q[1-4]$/.exec(label);
		const month = /^(\d{4}) ([A-Z]{3})$/.exec(label);
		if (year) {
			inData = true;
			annual.push({ year: Number(year[1]), ...readIndex(value, where) });
		} else if (quarter) {
			inData = true;
		} else if (month && ONS_MONTHS.includes(month[2])) {
			inData = true;
			monthly.push({ year: Number(month[1]), month: ONS_MONTHS.indexOf(month[2]) + 1, ...readIndex(value, where) });
		} else if (inData) {
			throw refuse("CPI_CSV_BAD_ROW", `${where} has the period "${label.slice(0, 40)}" among the figures, which is not a year, a quarter or a month`);
		} else if (label === "CDID") {
			cdid = value;
		}
	}
	if (cdid !== SERIES_ID) throw refuse("CPI_WRONG_SERIES", `the file is for series ${cdid === undefined ? "(none named)" : `"${String(cdid).slice(0, 20)}"`}, not ${SERIES_ID}`);
	return { annual: checkAnnual(annual), monthly: checkMonthly(monthly) };
}

/**
 * The table's years, one per year from 1800 to the last in either file.
 *
 * @param annual - Checked annual figures, from a parser.
 * @param monthly - Checked monthly figures, from a parser.
 * @returns `{ years, partial }`: each year's `{ year, value, decimals, months, source }`,
 *   and the latest year's `{ year, months }` when it stops before December.
 */
export function ukAnnualSeries(annual, monthly) {
	const years = checkAnnual(annual);
	const months = checkMonthly(monthly);
	if (years[0].year !== FIRST_YEAR) throw refuse("CPI_MISSING_YEAR", `the series starts in ${years[0].year}, not ${FIRST_YEAR}`);
	for (let i = 1; i < years.length; i++) {
		if (years[i].year !== years[i - 1].year + 1) throw refuse("CPI_MISSING_YEAR", `${years[i - 1].year + 1} has no annual figure`);
	}
	const byYear = new Map();
	for (const o of months) {
		if (!byYear.has(o.year)) byYear.set(o.year, []);
		byYear.get(o.year).push(o);
	}
	const mean = (list) => roundTo(list.reduce((sum, o) => sum + o.value, 0) / list.length, Math.max(...list.map((o) => o.decimals)));
	const out = years.map((a) => {
		const its = byYear.get(a.year) ?? [];
		if (its.length === 12) {
			const computed = mean(its);
			if (Math.abs(computed - a.value) > ANNUAL_TOLERANCE + 1e-9) {
				throw refuse("CPI_ANNUAL_MISMATCH", `${a.year} is ${a.value} in the annual figures, but its months average ${computed}, which is more than ${ANNUAL_TOLERANCE} away: the two files are not the same series`);
			}
		}
		return { year: a.year, value: a.value, decimals: a.decimals, months: its.length, source: "published" };
	});
	const lastAnnual = years[years.length - 1].year;
	const lastMonthly = months.length > 0 ? months[months.length - 1].year : lastAnnual;
	let partial = null;
	for (let year = lastAnnual + 1; year <= lastMonthly; year++) {
		const its = byYear.get(year) ?? [];
		if (its.length === 0) throw refuse("CPI_MISSING_YEAR", `${year} has neither an annual figure nor monthly ones`);
		for (let m = 1; m <= its[its.length - 1].month; m++) {
			if (!its.some((o) => o.month === m)) throw refuse("CPI_MONTH_MISSING", `${MONTH_NAMES[m - 1]} ${year} is missing, and ${year} has no annual figure to stand in for it`);
		}
		if (its.length < 12) {
			if (year !== lastMonthly) throw refuse("CPI_MONTH_MISSING", `${year} stops in ${MONTH_NAMES[its.length - 1]}, but later years have figures`);
			partial = { year, months: its.map((o) => o.month) };
		}
		out.push({ year, value: mean(its), decimals: Math.max(...its.map((o) => o.decimals)), months: its.length, source: "computed" });
	}
	return { years: out, partial };
}

/**
 * The generated part of `UkCpiTable.ts`: the header, the table and its range.
 *
 * @param series - What {@link ukAnnualSeries} returned.
 * @param meta - `{ source, retrieved }`: where the series came from, and when.
 * @returns TypeScript source, ending with {@link END_MARKER}.
 */
export function renderTable(series, meta) {
	const { years, partial } = series;
	if (!/^\d{4}-\d{2}-\d{2}$/.test(String(meta && meta.retrieved))) throw refuse("CPI_BAD_RETRIEVED", "the retrieval date must be written YYYY-MM-DD");
	const first = years[0].year;
	const last = years[years.length - 1].year;
	const lastPublished = years.filter((y) => y.source === "published").pop().year;
	const partialText = partial
		? `${partial.year} is partial: it averages the ${partial.months.length} months published so far, ${MONTH_NAMES[partial.months[0] - 1]} to ${MONTH_NAMES[partial.months[partial.months.length - 1] - 1]}, and moves as the rest are published.`
		: "Every year is complete.";
	const header = [
		"/**",
		" * UK long-term indicator of prices of consumer goods and services (ONS series",
		" * CDKO, January 1974 = 100) annual averages.",
		" *",
		" * Generated by `npm run data:cpi` (scripts/build-uk-cpi-table.mjs). Do not",
		" * edit the part above the END GENERATED line by hand: change the script or",
		" * its source and run it again.",
		" *",
		...wrap(`Source: Office for National Statistics, series ${SERIES_ID} (dataset MM23), ${meta.source}. Retrieved ${meta.retrieved}.`).map((l) => ` * ${l}`),
		" *",
		" * The index: CDKO is the ONS's own long-run consumer price series, which",
		" * chains RPI-era data before the CPI's start, so one series runs from 1800.",
		" * It is none of CPI, CPIH or RPI on its own.",
		" *",
		...wrap(`Method: each year to ${lastPublished} is the annual figure ONS publishes, as published. A later year is the mean of its published months, rounded to the one decimal ONS publishes. Every finished year with all twelve months in the source is checked against its annual figure, which must lie within ${ANNUAL_TOLERANCE} of the months' mean (ONS averages the unrounded months).`).map((l) => ` * ${l}`),
		...wrap(partialText).map((l) => ` * ${l}`),
		" *",
		...wrap(`Coverage: ${first}-${last} inclusive (${years.length} years). A year outside it produces \`INFLATION_YEAR_OUT_OF_RANGE\` rather than an extrapolation. Only an amount in pounds sterling is adjusted with it (see \`PriceIndices.ts\`). It is not authoritative for contracts, tax or cost-of-living escalation: consult ons.gov.uk for those.`).map((l) => ` * ${l}`),
		" */",
	];
	const rows = [];
	for (let i = 0; i < years.length; i += 5) {
		rows.push(`  ${years.slice(i, i + 5).map((e) => `${e.year}: ${e.value.toFixed(e.decimals)}`).join(", ")},`);
	}
	const partialConst = partial
		? `export const UK_CPI_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = { year: ${partial.year}, months: [${partial.months.join(", ")}] };`
		: "export const UK_CPI_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = null;";
	return [
		...header,
		"export const UK_CPI_TABLE: Readonly<Record<number, number>> = {",
		...rows,
		"} as const;",
		"",
		"/** Earliest year this table has data for. */",
		`export const UK_CPI_MIN_YEAR = ${first};`,
		"/** Most recent year in {@link UK_CPI_TABLE}; a later one is refused rather than extrapolated. */",
		`export const UK_CPI_MAX_YEAR = ${last};`,
		"",
		"/** The latest year when it stops before December, and the months it averages (one-based). */",
		partialConst,
		END_MARKER,
	].join("\n");
}

/** Wrap prose to the header's width. */
function wrap(text, width = 76) {
	const out = [];
	let line = "";
	for (const word of text.split(" ")) {
		if (line && line.length + 1 + word.length > width) {
			out.push(line);
			line = word;
		} else line = line ? `${line} ${word}` : word;
	}
	if (line) out.push(line);
	return out;
}

/**
 * The whole table file: the generated part, then whatever followed the end
 * marker in the existing file, kept as written.
 *
 * @param generated - What {@link renderTable} returned.
 * @param existing - The current file's text.
 * @returns The new file's text.
 */
export function spliceTable(generated, existing) {
	const at = String(existing).indexOf(END_MARKER);
	if (at === -1) throw refuse("CPI_NO_MARKER", `the table file has no "${END_MARKER}" line to splice after`);
	return generated + String(existing).slice(at + END_MARKER.length);
}

/**
 * Render figures as the mirror's two CSVs, for `--save-csv` after an ONS
 * fetch, so the recorded snapshot and the ONS file produce the same table.
 *
 * @returns `{ annual, monthly }`, each the text of one file.
 */
export function toMirrorCsvs(annual, monthly) {
	const a = ["Year,Price Index", ...checkAnnual(annual).map((o) => `${o.year},${o.value.toFixed(o.decimals)}`)];
	const m = ["Date,Price Index", ...checkMonthly(monthly).map((o) => `${monthKey(o.year, o.month)}-01,${o.value.toFixed(o.decimals)}`)];
	return { annual: `${a.join("\n")}\n`, monthly: `${m.join("\n")}\n` };
}

/** Fetch the ONS generator's CSV of the series. */
export async function fetchOns() {
	const res = await fetch(ONS_URL);
	if (!res.ok) throw refuse("CPI_ONS_REQUEST_FAILED", `the ONS generator answered ${res.status}`);
	return res.text();
}

/**
 * Where a mirror directory's files came from and when, from the record beside
 * them. A directory with no record is described as a copy of the mirror, and
 * needs `--retrieved`.
 *
 * @param dir - The directory.
 * @returns `{ source, retrieved }`, retrieved undefined when nothing records it.
 */
export function readSourceFile(dir) {
	const fallback = { source: "annual and monthly figures as mirrored by the Frictionless Data cpi-uk dataset (github.com/datasets/cpi-uk, data/cpi-uk-annual.csv and data/cpi-uk-monthly.csv)", retrieved: undefined };
	const file = path.join(dir, SOURCE_FILE);
	if (!fs.existsSync(file)) return fallback;
	let parsed;
	try {
		parsed = JSON.parse(fs.readFileSync(file, "utf8"));
	} catch {
		throw refuse("CPI_BAD_SOURCE_FILE", `${SOURCE_FILE} is not JSON`);
	}
	if (parsed === null || typeof parsed !== "object" || !Object.hasOwn(parsed, "source") || !Object.hasOwn(parsed, "retrieved") || typeof parsed.source !== "string" || typeof parsed.retrieved !== "string") {
		throw refuse("CPI_BAD_SOURCE_FILE", `${SOURCE_FILE} needs a "source" and a "retrieved" string`);
	}
	return { source: parsed.source, retrieved: parsed.retrieved };
}

/** Read `--name=value` and `--flag` arguments. */
function option(args, name) {
	const hit = args.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
	if (hit === undefined) return undefined;
	return hit.includes("=") ? hit.slice(hit.indexOf("=") + 1) : true;
}

/**
 * Build the table file's text from command-line options.
 *
 * @param args - The arguments, as `process.argv.slice(2)`.
 * @returns `{ text, out, existing }`: the new file, where it goes, and what is there now.
 */
export async function build(args) {
	const out = path.resolve(String(option(args, "out") ?? TABLE_PATH));
	const given = option(args, "retrieved");
	let series;
	let meta;
	if (option(args, "from-ons")) {
		const { annual, monthly } = parseOnsCsv(await fetchOns());
		series = ukAnnualSeries(annual, monthly);
		meta = { source: "the ONS time-series generator (www.ons.gov.uk)", retrieved: typeof given === "string" ? given : new Date().toISOString().slice(0, 10) };
		const saveCsv = option(args, "save-csv");
		if (typeof saveCsv === "string") {
			const dir = path.resolve(saveCsv);
			const files = toMirrorCsvs(annual, monthly);
			const recorded = { source: `${meta.source}, recorded in ${path.relative(REPO, dir).split(path.sep).join("/")}`, retrieved: meta.retrieved };
			fs.writeFileSync(path.join(dir, ANNUAL_FILE), files.annual);
			fs.writeFileSync(path.join(dir, MONTHLY_FILE), files.monthly);
			fs.writeFileSync(path.join(dir, SOURCE_FILE), `${JSON.stringify(recorded, null, "\t")}\n`);
		}
	} else {
		const mirror = option(args, "from-mirror");
		const dir = typeof mirror === "string" ? path.resolve(mirror) : FIXTURE_DIR;
		series = ukAnnualSeries(parseAnnualCsv(fs.readFileSync(path.join(dir, ANNUAL_FILE), "utf8")), parseMonthlyCsv(fs.readFileSync(path.join(dir, MONTHLY_FILE), "utf8")));
		meta = readSourceFile(dir);
		if (typeof given === "string") meta = { ...meta, retrieved: given };
	}
	const existing = fs.readFileSync(out, "utf8");
	return { text: spliceTable(renderTable(series, meta), existing), out, existing };
}

/**
 * Build, then either write the table or, with `--check`, compare it.
 *
 * @param args - The arguments, as `process.argv.slice(2)`.
 * @returns The exit status: 0, or 1 when `--check` found a difference or a check refused.
 */
export async function run(args) {
	try {
		const { text, out, existing } = await build(args);
		const relative = path.relative(REPO, out);
		if (option(args, "check")) {
			if (text !== existing) {
				console.error(`${relative} is not what scripts/build-uk-cpi-table.mjs generates. Run npm run data:cpi.`);
				return 1;
			}
			console.log(`${relative} matches its source.`);
			return 0;
		}
		fs.writeFileSync(out, text);
		console.log(`Wrote ${relative}.`);
		return 0;
	} catch (error) {
		console.error(error instanceof Error ? error.message : String(error));
		return 1;
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await run(process.argv.slice(2));
