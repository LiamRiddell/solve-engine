/**
 * Regenerates the bundled euro-area price index, `packages/engine/src/packages/finance/data/EuroHicpTable.ts`,
 * from the ECB's monthly series of Eurostat's harmonised index of consumer
 * prices (#756).
 *
 * The series is ICP.M.U2.N.000000.4.INX: the euro area (changing
 * composition), HICP overall index, 2015 = 100, neither seasonally nor working
 * day adjusted, compiled by Eurostat and published by the ECB, every month from
 * January 1996. The ECB discontinued this dataset (ICP) in February 2026, when
 * Eurostat's methodological changes to the HICP took effect, so its last month
 * is December 2025. The replacement dataset is a different series and is not
 * joined on: chaining one to the other would be a figure neither publisher
 * produced.
 *
 * It is a build step, not a runtime fetch, in the shape of the US table's
 * script (`build-cpi-table.mjs`, #700). The series comes from one of two places:
 *
 *   - `--from-ecb`: the ECB data API's CSV of the series ({@link ECB_URL}),
 *     the primary source. Needs network access to data-api.ecb.europa.eu.
 *   - `--from-csv=<file>`: a file in that same CSV shape. The default is the
 *     recorded snapshot in `scripts/fixtures/cpi/ecb-icp-hicp-euro-area.csv`,
 *     which is what the committed table was built from, so a plain run
 *     reproduces it.
 *
 * Where a CSV came from and when it was retrieved are recorded beside it, in
 * `<name>.source.json` (`{ "source", "retrieved" }`), which `--save-csv`
 * writes after an ECB fetch; a CSV without one needs `--retrieved=YYYY-MM-DD`.
 *
 * The method, which is Eurostat's for its annual average index
 * (`prc_hicp_aind`, unit INX_A_AVG): each year is the mean of its twelve
 * monthly values, rounded to the two decimals the series is published to. A
 * month missing from a finished year is refused, and the latest year, when it
 * stops before December, is marked partial.
 *
 * Every refusal is an Error whose message starts with a name in capitals
 * (`CPI_CSV_BAD_HEADER: ...`), so a test or a maintainer can tell which check
 * failed.
 *
 * Usage:
 *   npm run data:cpi                                      rebuild every bundled index
 *   npm run data:cpi -- --check                           exit 1 when a committed table differs
 *   node scripts/build-euro-hicp-table.mjs --check
 *   node scripts/build-euro-hicp-table.mjs --from-csv=<file> --retrieved=2026-10-01
 *   node scripts/build-euro-hicp-table.mjs --from-ecb --save-csv=scripts/fixtures/cpi/ecb-icp-hicp-euro-area.csv
 *   node scripts/build-euro-hicp-table.mjs --out=<file>   write somewhere other than the engine
 *
 * @module build-euro-hicp-table
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { readIndex, roundTo } from "./build-cpi-table.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The series the table is built from. */
export const SERIES_KEY = "ICP.M.U2.N.000000.4.INX";

/** The first year the series has. */
export const FIRST_YEAR = 1996;

/** The decimals the series is published to, and the annual average is rounded to. */
export const DECIMALS = 2;

/** The ECB data API's CSV of the series. */
export const ECB_URL = "https://data-api.ecb.europa.eu/service/data/ICP/M.U2.N.000000.4.INX?format=csvdata";

/** Where the generated table lives. */
export const TABLE_PATH = path.join(REPO, "packages/engine/src/packages/finance/data/EuroHicpTable.ts");

/** The recorded CSV snapshot the committed table was built from. */
export const FIXTURE_CSV = path.join(REPO, "scripts/fixtures/cpi/ecb-icp-hicp-euro-area.csv");

/** The line that ends the generated part of the table file; what follows it is kept as written. */
export const END_MARKER = "// END GENERATED BY scripts/build-euro-hicp-table.mjs";

/** The largest source accepted, in bytes. The real series is about 100 KB as the ECB writes it. */
export const MAX_SOURCE_BYTES = 2 * 1024 * 1024;

/** The most monthly rows accepted, a century of months with room to spare. */
export const MAX_ROWS = 12 * 150;

/** The columns the CSV must have; the ECB writes some thirty, and the rest are not used. */
export const REQUIRED_COLUMNS = Object.freeze(["KEY", "TIME_PERIOD", "OBS_VALUE"]);

const MONTH_NAMES = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

/** A named refusal. */
function refuse(name, detail) {
	return new Error(`${name}: ${detail}`);
}

/** `2025-10` for a year and a one-based month. */
function monthKey(year, month) {
	return `${year}-${String(month).padStart(2, "0")}`;
}

/**
 * Split CSV text into rows of cells, reading quoted cells the way RFC 4180
 * writes them: a cell in double quotes may hold commas, line breaks and a
 * doubled quote for a quote. The ECB quotes its long titles and comments.
 *
 * @param text - The file's text.
 * @returns The rows, each a list of cells.
 */
export function splitCsv(text) {
	const rows = [];
	let row = [];
	let cell = "";
	let quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"' && text[i + 1] === '"') {
				cell += '"';
				i++;
			} else if (c === '"') quoted = false;
			else cell += c;
		} else if (c === '"' && cell === "") quoted = true;
		else if (c === ",") {
			row.push(cell);
			cell = "";
		} else if (c === "\n" || c === "\r") {
			if (c === "\r" && text[i + 1] === "\n") i++;
			row.push(cell);
			rows.push(row);
			row = [];
			cell = "";
		} else cell += c;
	}
	if (quoted) throw refuse("CPI_CSV_BAD_ROW", "a quoted cell is never closed");
	if (cell !== "" || row.length > 0) {
		row.push(cell);
		rows.push(row);
	}
	return rows.filter((r) => !(r.length === 1 && r[0].trim() === ""));
}

/**
 * Check a list of monthly observations and order it: each year and month in
 * range, no month twice, nothing before 1996, nothing past the cap.
 *
 * @param observations - `{ year, month, value, decimals }` each, month one-based.
 * @returns The same observations sorted by date.
 */
export function checkObservations(observations) {
	if (!Array.isArray(observations) || observations.length === 0) throw refuse("CPI_NO_DATA", "the source has no monthly values");
	if (observations.length > MAX_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${observations.length} months, more than the ${MAX_ROWS} accepted`);
	const seen = new Map();
	for (const o of observations) {
		if (!Number.isInteger(o.year) || o.year < FIRST_YEAR || o.year > 9999) throw refuse("CPI_BAD_DATE", `the year ${o.year} is outside the series, which starts in ${FIRST_YEAR}`);
		if (!Number.isInteger(o.month) || o.month < 1 || o.month > 12) throw refuse("CPI_BAD_DATE", `${o.year} has a month numbered ${o.month}`);
		const key = monthKey(o.year, o.month);
		if (seen.has(key)) throw refuse("CPI_DUPLICATE_MONTH", `${key} appears twice`);
		seen.set(key, o);
	}
	return [...seen.values()].sort((a, b) => a.year - b.year || a.month - b.month);
}

/**
 * Parse the ECB data API's CSV of {@link SERIES_KEY}: a header row naming the
 * columns, then one row per month. Every row's KEY must be the series, so a
 * file of another series, or one mixing several, is refused.
 *
 * @param text - The file's text, LF or CRLF, with or without a trailing newline.
 * @returns The monthly observations, checked and sorted.
 */
export function parseEcbCsv(text) {
	if (typeof text !== "string") throw refuse("CPI_NO_DATA", "the source is not text");
	if (Buffer.byteLength(text, "utf8") > MAX_SOURCE_BYTES) throw refuse("CPI_SOURCE_TOO_LARGE", `the source is larger than ${MAX_SOURCE_BYTES} bytes`);
	const rows = splitCsv(text.replace(/^﻿/, ""));
	if (rows.length === 0) throw refuse("CPI_NO_DATA", "the source is empty");
	const header = rows[0].map((c) => c.trim());
	const at = Object.create(null);
	header.forEach((name, i) => {
		if (!Object.hasOwn(at, name)) at[name] = i;
	});
	for (const name of REQUIRED_COLUMNS) {
		if (!Object.hasOwn(at, name)) throw refuse("CPI_CSV_BAD_HEADER", `the header has no ${name} column`);
	}
	if (rows.length - 1 > MAX_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${rows.length - 1} rows, more than the ${MAX_ROWS} accepted`);
	const observations = [];
	for (let i = 1; i < rows.length; i++) {
		const where = `row ${i + 1}`;
		const cells = rows[i];
		if (cells.length !== header.length) throw refuse("CPI_CSV_BAD_ROW", `${where} has ${cells.length} cells, not the header's ${header.length}`);
		const key = cells[at.KEY].trim();
		if (key !== SERIES_KEY) throw refuse("CPI_WRONG_SERIES", `${where} is for series "${key.slice(0, 40)}", not ${SERIES_KEY}`);
		const date = /^(\d{4})-(\d{2})$/.exec(cells[at.TIME_PERIOD].trim());
		if (!date) throw refuse("CPI_BAD_DATE", `${where} has the period "${cells[at.TIME_PERIOD].trim().slice(0, 40)}", not a month written YYYY-MM`);
		const { value } = readIndex(cells[at.OBS_VALUE], where);
		observations.push({ year: Number(date[1]), month: Number(date[2]), value, decimals: DECIMALS });
	}
	return checkObservations(observations);
}

/**
 * The annual averages, one per year from 1996 to the last in the data.
 *
 * @param observations - Checked monthly observations, from the parser.
 * @returns `{ years, partial }`: each year's `{ year, value, decimals, months }`,
 *   and the latest year's `{ year, months }` when it stops before December.
 */
export function annualAverages(observations) {
	const checked = checkObservations(observations);
	const byYear = new Map();
	for (const o of checked) {
		if (!byYear.has(o.year)) byYear.set(o.year, []);
		byYear.get(o.year).push(o);
	}
	const first = checked[0].year;
	const last = checked[checked.length - 1].year;
	if (first !== FIRST_YEAR) throw refuse("CPI_MISSING_YEAR", `the series starts in ${first}, not ${FIRST_YEAR}`);
	const years = [];
	let partial = null;
	for (let year = first; year <= last; year++) {
		const months = byYear.get(year) ?? [];
		if (months.length === 0) throw refuse("CPI_MISSING_YEAR", `${year} has no monthly values`);
		const present = new Set(months.map((o) => o.month));
		const lastMonth = months[months.length - 1].month;
		const through = year === last ? lastMonth : 12;
		for (let m = 1; m <= through; m++) {
			if (!present.has(m)) throw refuse("CPI_MONTH_MISSING", `${MONTH_NAMES[m - 1]} ${year} is missing`);
		}
		if (through < 12) partial = { year, months: months.map((o) => o.month) };
		const value = roundTo(months.reduce((sum, o) => sum + o.value, 0) / months.length, DECIMALS);
		years.push({ year, value, decimals: DECIMALS, months: months.length });
	}
	return { years, partial };
}

/**
 * The generated part of `EuroHicpTable.ts`: the header, the table and its range.
 *
 * @param averages - What {@link annualAverages} returned.
 * @param meta - `{ source, retrieved }`: where the series came from, and when.
 * @returns TypeScript source, ending with {@link END_MARKER}.
 */
export function renderTable(averages, meta) {
	const { years, partial } = averages;
	if (!/^\d{4}-\d{2}-\d{2}$/.test(String(meta && meta.retrieved))) throw refuse("CPI_BAD_RETRIEVED", "the retrieval date must be written YYYY-MM-DD");
	const first = years[0].year;
	const last = years[years.length - 1].year;
	const partialText = partial
		? `${partial.year} is partial: it averages the ${partial.months.length} months published so far, ${MONTH_NAMES[partial.months[0] - 1]} to ${MONTH_NAMES[partial.months[partial.months.length - 1] - 1]}, and moves as the rest are published.`
		: `Every year is complete. The series' last month is December ${last}: the ECB discontinued this dataset in February 2026, when Eurostat's methodological changes to the HICP took effect, and its replacement is not joined on.`;
	const header = [
		"/**",
		" * Euro-area HICP (harmonised index of consumer prices, euro area changing",
		" * composition, overall index, 2015 = 100) annual averages.",
		" *",
		" * Generated by `npm run data:cpi` (scripts/build-euro-hicp-table.mjs). Do",
		" * not edit the part above the END GENERATED line by hand: change the script",
		" * or its source and run it again.",
		" *",
		...wrap(`Source: Eurostat, published by the European Central Bank as series ${SERIES_KEY}, ${meta.source}. Retrieved ${meta.retrieved}.`).map((l) => ` * ${l}`),
		" *",
		" * Method: each year is the mean of its twelve monthly values, rounded to the",
		" * two decimals the series is published to, which is how Eurostat derives",
		" * its annual average index (prc_hicp_aind, INX_A_AVG).",
		...wrap(partialText).map((l) => ` * ${l}`),
		" *",
		...wrap(`Coverage: ${first}-${last} inclusive (${years.length} years). A year outside it produces \`INFLATION_YEAR_OUT_OF_RANGE\` rather than an extrapolation, and so does a year before the euro began in 1999 (see \`EURO_FIRST_YEAR\` below). Only an amount in euros is adjusted with it (see \`PriceIndices.ts\`). It is not authoritative for contracts, tax or cost-of-living escalation: consult Eurostat for those.`).map((l) => ` * ${l}`),
		" */",
	];
	const rows = [];
	for (let i = 0; i < years.length; i += 5) {
		rows.push(`  ${years.slice(i, i + 5).map((e) => `${e.year}: ${e.value.toFixed(e.decimals)}`).join(", ")},`);
	}
	const partialConst = partial
		? `export const EURO_HICP_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = { year: ${partial.year}, months: [${partial.months.join(", ")}] };`
		: "export const EURO_HICP_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = null;";
	return [
		...header,
		"export const EURO_HICP_TABLE: Readonly<Record<number, number>> = {",
		...rows,
		"} as const;",
		"",
		"/** Earliest year this table has data for. */",
		`export const EURO_HICP_MIN_YEAR = ${first};`,
		"/** Most recent year in {@link EURO_HICP_TABLE}; a later one is refused rather than extrapolated. */",
		`export const EURO_HICP_MAX_YEAR = ${last};`,
		"",
		"/** The latest year when it stops before December, and the months it averages (one-based). */",
		partialConst,
		END_MARKER,
	].join("\n");
}

/** Wrap prose to the header's width. */
function wrap(text, width = 76) {
	const out = [];
	let line = "";
	for (const word of text.split(" ")) {
		if (line && line.length + 1 + word.length > width) {
			out.push(line);
			line = word;
		} else line = line ? `${line} ${word}` : word;
	}
	if (line) out.push(line);
	return out;
}

/**
 * The whole table file: the generated part, then whatever followed the end
 * marker in the existing file, kept as written.
 *
 * @param generated - What {@link renderTable} returned.
 * @param existing - The current file's text.
 * @returns The new file's text.
 */
export function spliceTable(generated, existing) {
	const at = String(existing).indexOf(END_MARKER);
	if (at === -1) throw refuse("CPI_NO_MARKER", `the table file has no "${END_MARKER}" line to splice after`);
	return generated + String(existing).slice(at + END_MARKER.length);
}

/** Fetch the ECB data API's CSV of the series. */
export async function fetchEcb() {
	const res = await fetch(ECB_URL);
	if (!res.ok) throw refuse("CPI_ECB_REQUEST_FAILED", `the ECB data API answered ${res.status}`);
	return res.text();
}

/** The file beside a CSV that records where it came from and when. */
export function sourceFileFor(csvFile) {
	return csvFile.replace(/\.csv$/i, "") + ".source.json";
}

/**
 * Where a CSV came from and when, from the file beside it. A CSV with no such
 * file is described as a copy of the ECB's, and needs `--retrieved`.
 *
 * @param csvFile - The CSV's path.
 * @returns `{ source, retrieved }`, retrieved undefined when nothing records it.
 */
export function readSourceFile(csvFile) {
	const fallback = { source: "monthly values in the ECB data API's CSV shape", retrieved: undefined };
	const file = sourceFileFor(csvFile);
	if (!fs.existsSync(file)) return fallback;
	let parsed;
	try {
		parsed = JSON.parse(fs.readFileSync(file, "utf8"));
	} catch {
		throw refuse("CPI_BAD_SOURCE_FILE", `${path.basename(file)} is not JSON`);
	}
	if (parsed === null || typeof parsed !== "object" || !Object.hasOwn(parsed, "source") || !Object.hasOwn(parsed, "retrieved") || typeof parsed.source !== "string" || typeof parsed.retrieved !== "string") {
		throw refuse("CPI_BAD_SOURCE_FILE", `${path.basename(file)} needs a "source" and a "retrieved" string`);
	}
	return { source: parsed.source, retrieved: parsed.retrieved };
}

/** Read `--name=value` and `--flag` arguments. */
function option(args, name) {
	const hit = args.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
	if (hit === undefined) return undefined;
	return hit.includes("=") ? hit.slice(hit.indexOf("=") + 1) : true;
}

/**
 * Build the table file's text from command-line options.
 *
 * @param args - The arguments, as `process.argv.slice(2)`.
 * @returns `{ text, out, existing }`: the new file, where it goes, and what is there now.
 */
export async function build(args) {
	const out = path.resolve(String(option(args, "out") ?? TABLE_PATH));
	const given = option(args, "retrieved");
	let averages;
	let meta;
	if (option(args, "from-ecb")) {
		const text = await fetchEcb();
		averages = annualAverages(parseEcbCsv(text));
		meta = { source: "the ECB data API (data-api.ecb.europa.eu)", retrieved: typeof given === "string" ? given : new Date().toISOString().slice(0, 10) };
		const saveCsv = option(args, "save-csv");
		if (typeof saveCsv === "string") {
			const file = path.resolve(saveCsv);
			const recorded = { source: `${meta.source}, recorded in ${path.relative(REPO, file).split(path.sep).join("/")}`, retrieved: meta.retrieved };
			fs.writeFileSync(file, text.replace(/\r\n/g, "\n"));
			fs.writeFileSync(sourceFileFor(file), `${JSON.stringify(recorded, null, "\t")}\n`);
		}
	} else {
		const csv = option(args, "from-csv");
		const file = typeof csv === "string" ? path.resolve(csv) : FIXTURE_CSV;
		averages = annualAverages(parseEcbCsv(fs.readFileSync(file, "utf8")));
		meta = readSourceFile(file);
		if (typeof given === "string") meta = { ...meta, retrieved: given };
	}
	const existing = fs.readFileSync(out, "utf8");
	return { text: spliceTable(renderTable(averages, meta), existing), out, existing };
}

/**
 * Build, then either write the table or, with `--check`, compare it.
 *
 * @param args - The arguments, as `process.argv.slice(2)`.
 * @returns The exit status: 0, or 1 when `--check` found a difference or a check refused.
 */
export async function run(args) {
	try {
		const { text, out, existing } = await build(args);
		const relative = path.relative(REPO, out);
		if (option(args, "check")) {
			if (text !== existing) {
				console.error(`${relative} is not what scripts/build-euro-hicp-table.mjs generates. Run npm run data:cpi.`);
				return 1;
			}
			console.log(`${relative} matches its source.`);
			return 0;
		}
		fs.writeFileSync(out, text);
		console.log(`Wrote ${relative}.`);
		return 0;
	} catch (error) {
		console.error(error instanceof Error ? error.message : String(error));
		return 1;
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await run(process.argv.slice(2));
