/**
 * Fails when a docs link goes to no page, or to a heading its page does not
 * have.
 *
 * Nothing checked the docs' internal links, and two anchors had broken without
 * anyone noticing: one pointed at a heading on a page that had none (the words
 * were the page's title), and one at a heading since renamed (#780). A broken
 * anchor still loads the page, so a reader lands at the top and has to hunt for
 * the part the sentence promised.
 *
 * For every content page, each root-relative link (`/guide/formatting/`, with
 * or without the trailing slash) must name a page on disk, and each fragment
 * (`#choosing-a-backend`) must name a heading on the page it goes to, by the
 * rule Astro uses to give a heading its id. A link to `#_top` always lands,
 * since that is the id Starlight gives the page title. A fragment on its own
 * (`#the-boundary`) is checked against the page it is written on.
 *
 * The boundary: links that leave the content tree are allowed by name rather
 * than checked. `/playground/` is the playground's build, which the pages
 * workflow copies into the site, and `/api/` is the reference starlight-typedoc
 * generates at build time, so neither is in the repository to be found. A path
 * with a file extension is a file the site serves, checked only against
 * `docs/public`. External addresses are not checked: a network call in a gate
 * makes it fail on a slow host, as the live weather calls already do. A
 * relative link (`../formatting/`) is reported, since the docs write internal
 * links root-relative and `rehype-base-links.mjs` adds the base path only to
 * those.
 *
 * Text matching rather than a markdown parser, for the reason
 * `check-sidebar.mjs` gives: a lint should not need a working docs install to
 * run. The reading is shared with `check-cheatsheet.mjs`.
 *
 * Usage:
 *   node scripts/check-doc-links.mjs
 *
 * `--root=<dir>` reads another checkout's docs tree instead, which is how the
 * spec runs it over fixture pages.
 *
 * @module check-doc-links
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { fragmentOf, headingIds, linkTargets, pageFiles, slugOf } from "./lib/markdown-links.mjs";

const rootArgument = process.argv.find((arg) => arg.startsWith("--root="));
const ROOT = rootArgument ? path.resolve(rootArgument.slice("--root=".length)) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = path.join(ROOT, "docs", "src", "content", "docs");
const PUBLIC = path.join(ROOT, "docs", "public");

/**
 * Root-relative prefixes that are not content pages, each with the reason. A
 * `Map`, so a prefix named after an inherited property is not read as listed.
 */
const OUTSIDE_CONTENT = new Map([
	["playground", "the playground's own build, copied into the site by .github/workflows/pages.yml"],
	["api", "the API reference, generated by starlight-typedoc at build time"],
]);

/**
 * Whether a slug falls under one of {@link OUTSIDE_CONTENT}'s prefixes.
 *
 * @param {string} slug - The slug a link names.
 * @returns {boolean} True when the link leaves the content tree by name.
 */
function outsideContent(slug) {
	const first = slug.split("/")[0];
	return OUTSIDE_CONTENT.has(first);
}

const pages = pageFiles(CONTENT);
if (pages.size === 0) {
	console.error("There are no pages under docs/src/content/docs, so there is nothing to check.");
	process.exit(1);
}

/** Heading ids per page, read once each and only for pages a fragment names. */
const idCache = new Map();
function idsOf(slug) {
	if (!idCache.has(slug)) idCache.set(slug, headingIds(fs.readFileSync(pages.get(slug), "utf8")));
	return idCache.get(slug);
}

const problems = [];
let checked = 0;
for (const [page, file] of [...pages].sort(([a], [b]) => a.localeCompare(b))) {
	const where = path.relative(CONTENT, file);
	for (const target of linkTargets(fs.readFileSync(file, "utf8"))) {
		// External addresses and mail links are not this check's to follow.
		if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("//")) continue;

		let slug;
		if (target.startsWith("#")) slug = page;
		else if (target.startsWith("/")) slug = slugOf(target);
		else {
			problems.push(`${where}: ${target} is a relative link; write it root-relative, from /`);
			continue;
		}

		checked++;
		if (outsideContent(slug)) continue;
		if (/\.[a-z0-9]+$/i.test(slug)) {
			if (!fs.existsSync(path.join(PUBLIC, slug))) problems.push(`${where}: ${target} is no file in docs/public`);
			continue;
		}
		if (!pages.has(slug)) {
			problems.push(`${where}: ${target} goes to no page`);
			continue;
		}
		const fragment = fragmentOf(target);
		if (fragment === null || fragment === "") continue;
		if (!idsOf(slug).has(fragment)) problems.push(`${where}: ${target} names no heading on ${slug || "the home page"}`);
	}
}

if (problems.length === 0) {
	console.log(`All ${checked} internal link(s) across ${pages.size} page(s) reach a page and, where they name one, a heading.`);
	process.exit(0);
}

console.error("These docs links are broken:");
for (const problem of problems) console.error(`  ${problem}`);
console.error("A page title is #_top; any other fragment is a heading's text, lowercased, punctuation dropped, spaces as hyphens.");
process.exit(1);
