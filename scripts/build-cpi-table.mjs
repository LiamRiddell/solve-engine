/**
 * Regenerates the bundled US price index, `packages/engine/src/packages/finance/data/CpiTable.ts`,
 * from the published Bureau of Labor Statistics series (#700).
 *
 * The table used to hold figures recalled from general knowledge, starting in
 * 1970, with its last two years chained from an IMF series. This builds it
 * from series CUUR0000SA0 (CPI-U, US city average, all items, not seasonally
 * adjusted, 1982-84=100), every year from 1913 to the latest month published.
 *
 * It is a build step, not a runtime fetch: the engine still makes no network
 * call for inflation. The series comes from one of two places:
 *
 *   - `--from-bls`: the BLS public API, the primary source. A POST per window
 *     of years (20 with a registration key in `BLS_API_KEY`, 10 without, the
 *     API's own limits). Needs network access to api.bls.gov.
 *   - `--from-csv=<file>`: a CSV in the Frictionless Data shape
 *     (`Date,Index,Inflation`, one row per month, `1913-01-01,9.8,`), the mirror
 *     of the same series at github.com/datasets/cpi-us. The default is the
 *     recorded snapshot in `scripts/fixtures/cpi/cpiai.csv`, which is what the
 *     committed table was built from, so a plain run reproduces it.
 *
 * Where a CSV came from and when it was retrieved are recorded beside it, in
 * `<name>.source.json` (`{ "source", "retrieved" }`), which `--save-csv` writes
 * after a BLS fetch; a CSV without one needs `--retrieved=YYYY-MM-DD`.
 *
 * The method, which is the one BLS uses: an annual average is the mean of the
 * year's published monthly values, rounded to the precision those values are
 * published to (one decimal before 2007, three from 2007). Where the source
 * carries the BLS annual figure (period M13 in an API response), that figure
 * is used as published. A month BLS never published is left out of the mean
 * only when it is a known gap, listed in {@link KNOWN_GAPS} with the reason
 * BLS gives; any other hole in a finished year is refused, since a mean over a
 * month lost in transit is a wrong number that looks right. The latest year,
 * when it stops before December, is marked partial with the months it
 * averages, and moves as the rest are published.
 *
 * Every refusal is an Error whose message starts with a name in capitals
 * (`CPI_CSV_BAD_HEADER: ...`), so a test or a maintainer can tell which check
 * failed.
 *
 * Usage:
 *   npm run data:cpi                                   rebuild from the recorded CSV
 *   npm run data:cpi -- --check                        exit 1 when the committed table differs
 *   node scripts/build-cpi-table.mjs --from-csv=<file> --retrieved=2026-10-01
 *   node scripts/build-cpi-table.mjs --from-bls --save-csv=scripts/fixtures/cpi/cpiai.csv
 *   node scripts/build-cpi-table.mjs --out=<file>      write somewhere other than the engine
 *
 * @module build-cpi-table
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The series the table is built from. */
export const SERIES_ID = "CUUR0000SA0";

/** The first year the series has. */
export const FIRST_YEAR = 1913;

/** Where the generated table lives. */
export const TABLE_PATH = path.join(REPO, "packages/engine/src/packages/finance/data/CpiTable.ts");

/** The recorded CSV snapshot the committed table was built from. */
export const FIXTURE_CSV = path.join(REPO, "scripts/fixtures/cpi/cpiai.csv");

/** The line that ends the generated part of the table file; what follows it is kept as written. */
export const END_MARKER = "// END GENERATED BY scripts/build-cpi-table.mjs";

/**
 * The largest source accepted, in bytes. The real series is about 30 KB as CSV
 * and grows by twelve rows a year; a file far past this is not the series.
 */
export const MAX_SOURCE_BYTES = 1024 * 1024;

/** The most monthly rows accepted, a century and a half of months with room to spare. */
export const MAX_ROWS = 12 * 200;

/**
 * Months BLS did not publish, with the reason it gives and the annual average
 * BLS published for that year over the months it has. A finished year with one
 * of these missing is averaged over the months it has, as BLS averaged it, and
 * the result must equal the published figure or the build is refused; any
 * other missing month is refused outright.
 */
export const KNOWN_GAPS = Object.freeze({
	"2025-10": Object.freeze({ reason: "Data unavailable due to the 2025 lapse in appropriations", publishedAnnual: 321.943 }),
});

const MONTH_NAMES = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

/** A named refusal. */
function refuse(name, detail) {
	return new Error(`${name}: ${detail}`);
}

/** `2025-10` for a year and a one-based month. */
function monthKey(year, month) {
	return `${year}-${String(month).padStart(2, "0")}`;
}

/**
 * Read an index value as BLS writes it: a positive decimal with no sign,
 * exponent or thousands separator.
 *
 * @param text - The value's text.
 * @param where - Where it came from, for the refusal.
 * @returns The value and the number of decimals it was written with.
 */
export function readIndex(text, where) {
	const s = String(text).trim();
	if (!/^\d{1,6}(\.\d{1,6})?$/.test(s)) throw refuse("CPI_BAD_INDEX", `${where} has the index "${s.slice(0, 40)}", which is not a positive decimal`);
	const value = Number(s);
	if (!Number.isFinite(value) || value <= 0) throw refuse("CPI_BAD_INDEX", `${where} has the index ${s}, which is not above zero`);
	return { value, decimals: (s.split(".")[1] ?? "").length };
}

/**
 * Check a list of monthly observations and order it: each year and month in
 * range, no month twice, nothing before 1913, nothing past the cap.
 *
 * @param observations - `{ year, month, value, decimals }` each, month one-based.
 * @returns The same observations sorted by date.
 */
export function checkObservations(observations) {
	if (!Array.isArray(observations) || observations.length === 0) throw refuse("CPI_NO_DATA", "the source has no monthly values");
	if (observations.length > MAX_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${observations.length} months, more than the ${MAX_ROWS} accepted`);
	const seen = new Map();
	for (const o of observations) {
		if (!Number.isInteger(o.year) || o.year < FIRST_YEAR || o.year > 9999) throw refuse("CPI_BAD_DATE", `the year ${o.year} is outside the series, which starts in ${FIRST_YEAR}`);
		if (!Number.isInteger(o.month) || o.month < 1 || o.month > 12) throw refuse("CPI_BAD_DATE", `${o.year} has a month numbered ${o.month}`);
		const key = monthKey(o.year, o.month);
		if (seen.has(key)) throw refuse("CPI_DUPLICATE_MONTH", `${key} appears twice`);
		seen.set(key, o);
	}
	return [...seen.values()].sort((a, b) => a.year - b.year || a.month - b.month);
}

/**
 * Parse the mirror's CSV: a `Date,Index,Inflation` header, then one row per
 * month dated the first of the month. The `Inflation` column is the mirror's
 * own month-on-month change and is not used.
 *
 * @param text - The file's text, LF or CRLF, with or without a trailing newline.
 * @returns The monthly observations, checked and sorted.
 */
export function parseMirrorCsv(text) {
	if (typeof text !== "string") throw refuse("CPI_NO_DATA", "the source is not text");
	if (Buffer.byteLength(text, "utf8") > MAX_SOURCE_BYTES) throw refuse("CPI_SOURCE_TOO_LARGE", `the source is larger than ${MAX_SOURCE_BYTES} bytes`);
	const lines = text.replace(/^﻿/, "").split(/\r?\n/);
	while (lines.length > 0 && lines[lines.length - 1].trim() === "") lines.pop();
	if (lines.length === 0) throw refuse("CPI_NO_DATA", "the source is empty");
	const header = lines[0].split(",").map((c) => c.trim());
	if (header.length !== 3 || header[0] !== "Date" || header[1] !== "Index" || header[2] !== "Inflation") {
		throw refuse("CPI_CSV_BAD_HEADER", `the header is "${lines[0].slice(0, 80)}", not "Date,Index,Inflation"`);
	}
	if (lines.length - 1 > MAX_ROWS) throw refuse("CPI_SOURCE_TOO_LARGE", `the source has ${lines.length - 1} rows, more than the ${MAX_ROWS} accepted`);
	const observations = [];
	for (let i = 1; i < lines.length; i++) {
		const where = `line ${i + 1}`;
		const cells = lines[i].split(",");
		if (cells.length !== 3) throw refuse("CPI_CSV_BAD_ROW", `${where} has ${cells.length} cells, not 3`);
		const date = /^(\d{4})-(\d{2})-01$/.exec(cells[0].trim());
		if (!date) throw refuse("CPI_BAD_DATE", `${where} has the date "${cells[0].trim().slice(0, 40)}", not the first of a month written YYYY-MM-01`);
		const { value, decimals } = readIndex(cells[1], where);
		observations.push({ year: Number(date[1]), month: Number(date[2]), value, decimals });
	}
	return checkObservations(observations);
}

/**
 * Parse a BLS public API response for {@link SERIES_ID}. A month BLS has no
 * value for is written `-` and left out; an M13 row is the published annual
 * average and is returned separately.
 *
 * @param response - The parsed JSON of one or more responses (an array is merged).
 * @returns `{ observations, annual }`, annual keyed by year.
 */
export function parseBlsResponse(response) {
	const responses = Array.isArray(response) ? response : [response];
	const observations = [];
	const annual = Object.create(null);
	for (const r of responses) {
		if (r === null || typeof r !== "object" || r.status !== "REQUEST_SUCCEEDED") {
			const message = r && Array.isArray(r.message) ? r.message.join(" ").slice(0, 200) : "";
			throw refuse("CPI_BLS_REQUEST_FAILED", `the BLS API did not succeed${message ? `: ${message}` : ""}`);
		}
		const series = r.Results && Array.isArray(r.Results.series) ? r.Results.series : [];
		const ours = series.find((s) => s && s.seriesID === SERIES_ID);
		if (!ours || !Array.isArray(ours.data)) throw refuse("CPI_BLS_NO_SERIES", `the response has no ${SERIES_ID} series`);
		for (const row of ours.data) {
			const year = Number(row && row.year);
			const period = /^M(\d{2})$/.exec(String(row && row.period));
			if (!period) continue;
			const where = `${row.year} ${row.period}`;
			if (String(row.value).trim() === "-") continue;
			const { value, decimals } = readIndex(row.value, where);
			const month = Number(period[1]);
			if (month === 13) {
				if (!Number.isInteger(year)) throw refuse("CPI_BAD_DATE", `${where} has no year`);
				annual[year] = { value, decimals };
			} else {
				observations.push({ year, month, value, decimals });
			}
		}
	}
	return { observations: checkObservations(observations), annual };
}

/**
 * Round half away from zero to a number of decimals, through the decimal text
 * so 207.3425 does not land on 207.342 by binary accident.
 */
export function roundTo(value, decimals) {
	const factor = 10 ** decimals;
	return Math.round(Number((value * factor).toPrecision(15))) / factor;
}

/**
 * The annual averages, one per year from the first in the data to the last.
 *
 * @param observations - Checked monthly observations, from a parser.
 * @param annual - Published annual averages by year (BLS M13), used where present.
 * @returns `{ years, partial }`: each year's `{ year, value, decimals, months, source }`,
 *   and the latest year's `{ year, months }` when it stops before December.
 */
export function annualAverages(observations, annual = Object.create(null)) {
	const checked = checkObservations(observations);
	const byYear = new Map();
	for (const o of checked) {
		if (!byYear.has(o.year)) byYear.set(o.year, []);
		byYear.get(o.year).push(o);
	}
	const first = checked[0].year;
	const last = checked[checked.length - 1].year;
	if (first !== FIRST_YEAR) throw refuse("CPI_MISSING_YEAR", `the series starts in ${first}, not ${FIRST_YEAR}`);
	const years = [];
	let partial = null;
	for (let year = first; year <= last; year++) {
		const months = byYear.get(year) ?? [];
		if (months.length === 0) throw refuse("CPI_MISSING_YEAR", `${year} has no monthly values`);
		const present = new Set(months.map((o) => o.month));
		// The latest year is partial when it stops before December. A year that
		// reaches December with a known gap in it (2025) is finished.
		const lastMonth = months[months.length - 1].month;
		if (year === last && lastMonth < 12) {
			for (let m = 1; m < lastMonth; m++) {
				if (!present.has(m) && !Object.hasOwn(KNOWN_GAPS, monthKey(year, m))) throw refuse("CPI_MONTH_MISSING", `${MONTH_NAMES[m - 1]} ${year} is missing before later months of the partial year`);
			}
			partial = { year, months: months.map((o) => o.month) };
		} else {
			for (let m = 1; m <= 12; m++) {
				if (!present.has(m) && !Object.hasOwn(KNOWN_GAPS, monthKey(year, m))) throw refuse("CPI_MONTH_MISSING", `${MONTH_NAMES[m - 1]} ${year} is missing, and is not a month BLS left unpublished`);
			}
		}
		const published = Object.hasOwn(annual, year) ? annual[year] : undefined;
		if (published && partial === null) {
			years.push({ year, value: published.value, decimals: published.decimals, months: months.length, source: "published" });
			continue;
		}
		const decimals = Math.max(...months.map((o) => o.decimals));
		const value = roundTo(months.reduce((sum, o) => sum + o.value, 0) / months.length, decimals);
		for (let m = 1; m <= 12 && partial === null; m++) {
			const gap = present.has(m) ? undefined : KNOWN_GAPS[monthKey(year, m)];
			if (gap && value !== gap.publishedAnnual) throw refuse("CPI_GAP_MISMATCH", `${year} averages ${value} over its ${months.length} months, not the ${gap.publishedAnnual} BLS published`);
		}
		years.push({ year, value, decimals, months: months.length, source: "computed" });
	}
	return { years, partial };
}

/** The gaps a set of years actually has, each as a sentence for the header. */
function gapsIn(years) {
	const out = [];
	for (const [key, gap] of Object.entries(KNOWN_GAPS)) {
		const [y, m] = key.split("-").map(Number);
		const year = years.find((e) => e.year === y);
		if (year && year.months < 12) {
			out.push(
				`${MONTH_NAMES[m - 1]} ${y} was never published (${gap.reason.charAt(0).toLowerCase()}${gap.reason.slice(1)}), so ${y} is the mean of its ${year.months} published months, ${year.value.toFixed(year.decimals)}, which is the annual average BLS published for it.`,
			);
		}
	}
	return out;
}

/**
 * The generated part of `CpiTable.ts`: the header, the table and its range.
 *
 * @param averages - What {@link annualAverages} returned.
 * @param meta - `{ source, retrieved }`: where the series came from, and when.
 * @returns TypeScript source, ending with {@link END_MARKER}.
 */
export function renderTable(averages, meta) {
	const { years, partial } = averages;
	if (!/^\d{4}-\d{2}-\d{2}$/.test(String(meta && meta.retrieved))) throw refuse("CPI_BAD_RETRIEVED", "the retrieval date must be written YYYY-MM-DD");
	const first = years[0].year;
	const last = years[years.length - 1].year;
	const gaps = gapsIn(years);
	const partialText = partial
		? `${partial.year} is partial: it averages the ${partial.months.length} months published so far, ${MONTH_NAMES[partial.months[0] - 1]} to ${MONTH_NAMES[partial.months[partial.months.length - 1] - 1]}, and moves as the rest are published.`
		: `Every year is complete.`;
	const header = [
		"/**",
		" * U.S. CPI-U (Consumer Price Index for All Urban Consumers, U.S. city",
		" * average, all items, not seasonally adjusted, 1982-84=100) annual averages.",
		" *",
		" * Generated by `npm run data:cpi` (scripts/build-cpi-table.mjs). Do not edit",
		" * the part above the END GENERATED line by hand: change the script or its",
		" * source and run it again.",
		" *",
		...wrap(`Source: U.S. Bureau of Labor Statistics, series ${SERIES_ID}, ${meta.source}. Retrieved ${meta.retrieved}.`).map((l) => ` * ${l}`),
		" *",
		" * Method: each year is the mean of its published monthly values, rounded to",
		" * the precision BLS publishes them to (one decimal before 2007, three from",
		" * 2007), which is how BLS derives its annual average; a published annual",
		" * average (BLS period M13) is used as it stands where the source has one.",
		...(gaps.length > 0
			? gaps.flatMap((g) => wrap(g)).map((l) => ` * ${l}`)
			: []),
		...wrap(partialText).map((l) => ` * ${l}`),
		" *",
		` * Coverage: ${first}-${last} inclusive (${years.length} years). A year outside it`,
		" * produces `INFLATION_YEAR_OUT_OF_RANGE` rather than an extrapolation. The",
		" * index is the US one, so only an amount in US dollars is adjusted with it",
		" * (see `InflationAmount.ts`). It is not authoritative for contracts, tax or",
		" * cost-of-living escalation: consult bls.gov/cpi for those.",
		" */",
	];
	const rows = [];
	for (let i = 0; i < years.length; i += 5) {
		rows.push(`  ${years.slice(i, i + 5).map((e) => `${e.year}: ${e.value.toFixed(e.decimals)}`).join(", ")},`);
	}
	const partialConst = partial
		? `export const CPI_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = { year: ${partial.year}, months: [${partial.months.join(", ")}] };`
		: "export const CPI_PARTIAL_YEAR: { readonly year: number; readonly months: readonly number[] } | null = null;";
	return [
		...header,
		"export const CPI_TABLE: Readonly<Record<number, number>> = {",
		...rows,
		"} as const;",
		"",
		"/** Earliest year this table has data for, used for range-check error messages. */",
		`export const CPI_MIN_YEAR = ${first};`,
		"/**",
		" * Most recent year in {@link CPI_TABLE}.",
		" *",
		" * A request beyond this is rejected rather than extrapolated, since inflation",
		" * past the last published figure is a forecast and not a conversion.",
		" */",
		`export const CPI_MAX_YEAR = ${last};`,
		"",
		"/** The latest year when it stops before December, and the months it averages (one-based). */",
		partialConst,
		END_MARKER,
	].join("\n");
}

/** Wrap prose to the header's width. */
function wrap(text, width = 76) {
	const out = [];
	let line = "";
	for (const word of text.split(" ")) {
		if (line && line.length + 1 + word.length > width) {
			out.push(line);
			line = word;
		} else line = line ? `${line} ${word}` : word;
	}
	if (line) out.push(line);
	return out;
}

/**
 * The whole table file: the generated part, then whatever followed the end
 * marker in the existing file (the lookup functions), kept as written.
 *
 * @param generated - What {@link renderTable} returned.
 * @param existing - The current file's text.
 * @returns The new file's text.
 */
export function spliceTable(generated, existing) {
	const at = String(existing).indexOf(END_MARKER);
	if (at === -1) throw refuse("CPI_NO_MARKER", `the table file has no "${END_MARKER}" line to splice after`);
	return generated + String(existing).slice(at + END_MARKER.length);
}

/**
 * Render observations as the mirror's CSV shape, for `--save-csv` after a BLS
 * fetch, so the recorded snapshot and the API produce the same table.
 */
export function toMirrorCsv(observations) {
	const lines = ["Date,Index,Inflation"];
	let previous = null;
	for (const o of checkObservations(observations)) {
		const change = previous === null ? "" : (((o.value - previous) / previous) * 100).toFixed(2);
		lines.push(`${monthKey(o.year, o.month)}-01,${o.value.toFixed(o.decimals)},${change}`);
		previous = o.value;
	}
	return `${lines.join("\n")}\n`;
}

/**
 * Fetch the series from the BLS public API, one POST per window of years.
 *
 * @param endYear - The last year to ask for, normally the current one.
 * @param key - A BLS registration key, or undefined for the unregistered limits.
 * @returns The parsed responses, for {@link parseBlsResponse}.
 */
export async function fetchBls(endYear, key = process.env.BLS_API_KEY) {
	const window = key ? 20 : 10;
	const responses = [];
	for (let start = FIRST_YEAR; start <= endYear; start += window) {
		const body = { seriesid: [SERIES_ID], startyear: String(start), endyear: String(Math.min(start + window - 1, endYear)), annualaverage: true };
		if (key) body.registrationkey = key;
		const res = await fetch(`https://api.bls.gov/publicAPI/v2/timeseries/data/`, {
			method: "POST",
			headers: { "Content-Type": "application/json" },
			body: JSON.stringify(body),
		});
		if (!res.ok) throw refuse("CPI_BLS_REQUEST_FAILED", `the BLS API answered ${res.status} for ${body.startyear} to ${body.endyear}`);
		responses.push(await res.json());
	}
	return responses;
}

/** Read `--name=value` and `--flag` arguments. */
function option(args, name) {
	const hit = args.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
	if (hit === undefined) return undefined;
	return hit.includes("=") ? hit.slice(hit.indexOf("=") + 1) : true;
}

/**
 * Build the table file's text from command-line options.
 *
 * @param args - The arguments, as `process.argv.slice(2)`.
 * @returns `{ text, out }`: the new file and where it goes.
 */
export async function build(args) {
	const out = path.resolve(String(option(args, "out") ?? TABLE_PATH));
	const given = option(args, "retrieved");
	let averages;
	let meta;
	if (option(args, "from-bls")) {
		const responses = await fetchBls(new Date().getUTCFullYear());
		const { observations, annual } = parseBlsResponse(responses);
		averages = annualAverages(observations, annual);
		meta = { source: "the BLS public API (api.bls.gov, v2 timeseries)", retrieved: typeof given === "string" ? given : new Date().toISOString().slice(0, 10) };
		const saveCsv = option(args, "save-csv");
		if (typeof saveCsv === "string") {
			const file = path.resolve(saveCsv);
			const recorded = { source: `${meta.source}, recorded in ${path.relative(REPO, file).split(path.sep).join("/")}`, retrieved: meta.retrieved };
			fs.writeFileSync(file, toMirrorCsv(observations));
			fs.writeFileSync(sourceFileFor(file), `${JSON.stringify(recorded, null, "\t")}\n`);
		}
	} else {
		const csv = option(args, "from-csv");
		const file = typeof csv === "string" ? path.resolve(csv) : FIXTURE_CSV;
		averages = annualAverages(parseMirrorCsv(fs.readFileSync(file, "utf8")));
		meta = readSourceFile(file);
		if (typeof given === "string") meta = { ...meta, retrieved: given };
	}
	const existing = fs.readFileSync(out, "utf8");
	return { text: spliceTable(renderTable(averages, meta), existing), out, existing };
}

/** The file beside a CSV that records where it came from and when: `cpiai.csv` has `cpiai.source.json`. */
export function sourceFileFor(csvFile) {
	return csvFile.replace(/\.csv$/i, "") + ".source.json";
}

/**
 * Where a CSV came from and when, from the file beside it. A CSV with no such
 * file is described as a copy of the mirror, and needs `--retrieved`.
 *
 * @param csvFile - The CSV's path.
 * @returns `{ source, retrieved }`, retrieved undefined when nothing records it.
 */
export function readSourceFile(csvFile) {
	const fallback = { source: "monthly values as mirrored by the Frictionless Data cpi-us dataset (github.com/datasets/cpi-us, data/cpiai.csv)", retrieved: undefined };
	const file = sourceFileFor(csvFile);
	if (!fs.existsSync(file)) return fallback;
	let parsed;
	try {
		parsed = JSON.parse(fs.readFileSync(file, "utf8"));
	} catch {
		throw refuse("CPI_BAD_SOURCE_FILE", `${path.basename(file)} is not JSON`);
	}
	if (parsed === null || typeof parsed !== "object" || typeof parsed.source !== "string" || typeof parsed.retrieved !== "string") {
		throw refuse("CPI_BAD_SOURCE_FILE", `${path.basename(file)} needs a "source" and a "retrieved" string`);
	}
	return { source: parsed.source, retrieved: parsed.retrieved };
}

async function main() {
	const args = process.argv.slice(2);
	try {
		const { text, out, existing } = await build(args);
		const relative = path.relative(REPO, out);
		if (option(args, "check")) {
			if (text !== existing) {
				console.error(`${relative} is not what scripts/build-cpi-table.mjs generates. Run npm run data:cpi.`);
				process.exit(1);
			}
			console.log(`${relative} matches its source.`);
			return;
		}
		fs.writeFileSync(out, text);
		console.log(`Wrote ${relative}.`);
	} catch (error) {
		console.error(error instanceof Error ? error.message : String(error));
		process.exit(1);
	}
}

